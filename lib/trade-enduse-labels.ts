/** Special entries, by flow: kept in every sum, never ranked as a kind of good. Plain names for the footnote. */
export const ENDUSE_SPECIAL: Readonly<Record<EnduseFlow, Readonly<Record<string, string>>>> = {
  exports: {
    "60000": "Minimum-value shipments", // $54.7B in 2025: too small to be itemized, estimated
    "60010": "Miscellaneous domestic exports & special transactions", // $10.2B
    "60040": "Undocumented exports to Canada", // $0.3B (2024 on)
  },
  imports: {
    "50020": "U.S. goods returned & reimports", // $103.6B
    "50030": "Minimum-value shipments", // $30.1B
    "50040": "Movies, miscellaneous imports & special transactions", // $11.5B
  },
};

export const isSpecialEnduse = (flow: EnduseFlow, code: string) => code in ENDUSE_SPECIAL[flow];

/** The plain name of a category on a flow, or undefined if the code is unknown. */
export const enduseLabel = (flow: EnduseFlow, code: string): string | undefined => ENDUSE_SPECIAL[flow][code] ?? ENDUSE_LABELS[flow][code];
