/**
 * Plain-English names for the Census end-use categories (5-digit codes), as the goods-by-use files use them
 * (`trade_enduse_*`). Census's own descriptions are upper-case and abbreviated ("CELL PHONES AND OTHER HOUSEHOLD
 * GOODS, N.E.C."); these are the names a reader uses. Hand-written, sentence case, keyed by FLOW and then code,
 * because the two flows use different code lists and the same code can mean different things (00000 is wheat on
 * exports and green coffee on imports; 50020 is military aircraft engines on exports and U.S. goods returned on
 * imports). `SHARED` holds only codes whose Census description is the same on both flows.
 *
 * Special entries are not a kind of good: they are minimum-value shipments, returned goods and other
 * transactions Census classes by how they cross the border. They are part of every total (the categories sum to a
 * partner's total only with them), so the files keep them, but a "top categories" list skips them and names them
 * in a footnote. See docs/TRADE_METHODOLOGY.md ("Goods by use").
 *
 * The transform fails if the data carries a category missing from this file, and a test checks both directions.
 */
