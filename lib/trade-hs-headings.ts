/** Words Census abbreviates in its descriptions, spelled out for the fallback name. */
const ABBREVIATIONS: Readonly<Record<string, string>> = {
  ACCESS: "accessories",
  ART: "articles",
  ARTS: "articles",
  CHEM: "chemical",
  EQUIP: "equipment",
  FR: "fresh",
  INCL: "including",
  MACH: "machines",
  MFR: "manufactured",
  MFRS: "manufactures",
  PREP: "prepared",
  PRES: "preserved",
  PT: "parts",
  PTS: "parts",
  VEG: "vegetable",
};

/**
 * A readable name from Census's description, for a heading with no hand name:
 * the first clause (up to the first semicolon), "NESOI" ("not elsewhere
 * specified or indicated") and a trailing "ETC" dropped, common abbreviations
 * spelled out, in sentence case. "PARTS ETC FOR MACHINE TOOLS OF HEAD 8456 TO
 * 8465" becomes "Parts for machine tools of head 8456 to 8465": plain, if not
 * elegant.
 */
export function fallbackHeadingName(censusDesc: string): string {
  const first = censusDesc.split(";")[0];
  const words = first
    .replace(/\bNESOI\b|\bNES\b/g, "")
    .replace(/\bETC\b\.?/g, "")
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => {
      const bare = w.replace(/[,.]$/, "");
      const tail = w.slice(bare.length);
      return (ABBREVIATIONS[bare] ?? bare.toLowerCase()) + tail;
    });
  const text = words.join(" ").replace(/\s+,/g, ",").replace(/[,\s]+$/, "").trim();
  return text ? text[0].toUpperCase() + text.slice(1) : censusDesc;
}

/** The name a card shows for an ordinary heading: the hand-written one, else the cleaned-up Census description, else the code. */
export function headingName(hs: string, censusDesc: string | undefined): string {
  return HS_HEADINGS[hs] ?? (censusDesc ? fallbackHeadingName(censusDesc) : `Heading ${hs}`);
}
